#!/bin/sh
# Writes docs/evidence/<date>.md: what the ADRs' verification ran (RUN, PASS,
# SKIP, FAIL per named test, from go test -json), the divergences still
# unclassified per area, and the result of every oracle mutation script. The
# increment records link the report instead of copying its numbers (NUCLEO.md §3).
set -eu
repo=$(cd "$(dirname "$0")/.." && pwd)
cd "$repo"
python3 -I - "$repo" <<'PY'
import collections, datetime, glob, json, os, re, subprocess, sys

repo = sys.argv[1]
date = datetime.date.today().isoformat()
head = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()
dirty = subprocess.run(["git", "status", "--porcelain"], capture_output=True, text=True).stdout.strip()
out = [f"# Evidence {date}", "", f"Generated by `make evidence` at {head}{' with uncommitted changes' if dirty else ''}.", ""]

# The same reading of an ADR's verification as adr_test.go: a test, with or
# without backticks, and a family Test…* by its prefix.
NAMED = re.compile(r"`?((?:Test|Fuzz|Benchmark)[A-Z][A-Za-z0-9_]*)(\*?)`?")
named = set()
for adr in sorted(glob.glob("docs/adr/*.md")):
    text = open(adr).read()
    # The section exactly as adr_test.go cuts it: the heading on a line of its
    # own, so that a "### Verificación manual" before it is not taken for it.
    heading = "\n## Verificación\n"
    if text.count(heading) != 1:
        sys.exit(f"{adr}: {text.count(heading)} «## Verificación» sections, want one")
    verification = text.split(heading, 1)[1].split("\n## ", 1)[0]
    named |= {(m.group(1), m.group(2) == "*") for m in NAMED.finditer(verification)}

listed = subprocess.run(["go", "test", "-list", ".", "./..."], capture_output=True, text=True)
if listed.returncode != 0:
    sys.exit("go test -list failed:\n" + (listed.stdout + listed.stderr)[-3000:])
every = {l for l in listed.stdout.split() if re.match(r"^(Test|Fuzz|Benchmark|Example)", l)}
tests = sorted({t for name, family in named for t in every if t == name or family and t.startswith(name)})
missing = sorted(name for name, family in named if not any(t == name or family and t.startswith(name) for t in every))

out += ["## Tests the ADRs name", "", "| Test | RUN | PASS | SKIP | FAIL |", "|---|---|---|---|---|"]
run = subprocess.run(["go", "test", "-json", "-count=1", "-run", "^(" + "|".join(tests) + ")$", "./..."],
                     capture_output=True, text=True)
counts = collections.defaultdict(collections.Counter)
for line in run.stdout.splitlines():
    try:
        e = json.loads(line)
    except json.JSONDecodeError:
        continue
    test = e.get("Test")
    if test and e.get("Action") in ("run", "pass", "skip", "fail"):
        counts[test.split("/")[0]][e["Action"]] += 1
problems = [f"`{name}` is named by an ADR and no package has it" for name in missing]
for test in tests:
    c = counts.get(test, collections.Counter())
    out.append(f"| `{test}` | {c['run']} | {c['pass']} | {c['skip']} | {c['fail']} |")
    if c["run"] == 0:
        problems.append(f"`{test}` did not run")
    if c["skip"]:
        problems.append(f"`{test}` skipped {c['skip']} times")
    if c["fail"]:
        problems.append(f"`{test}` failed")
if run.returncode != 0 and not problems:
    problems.append("go test failed:\n```\n" + (run.stdout + run.stderr)[-3000:] + "\n```")
out += ["", "RUN counts subtests too; a test with no RUN did not run.", ""]
if problems:
    out += ["## Problems", ""] + [f"- {p}" for p in problems] + [""]

CLASSES = ["own defect", "reference defect", "deliberate", "undecided", "unclassified"]
out += ["## Divergences by class", "", "| Area | " + " | ".join(CLASSES) + " | Recorded |",
        "|---|" + "---|" * (len(CLASSES) + 1)]
for path in sorted(glob.glob("testdata/snapshots/*.divergences.tsv")):
    rows = [l.split("\t") for l in open(path).read().splitlines() if l and not l.startswith("#")]
    counts = collections.Counter(r[2] for r in rows if len(r) == 7)
    cells = " | ".join(str(counts[c]) for c in CLASSES)
    out.append(f"| {os.path.basename(path).split('.')[0]} | {cells} | {len(rows)} |")
out.append("")

out += ["## Oracle mutations", ""]
# A mutation of the evidence itself runs this script without the mutations,
# which would otherwise run inside their own copies again.
scripts = [] if os.environ.get("CQL_EVIDENCE_NO_MUTATIONS") else sorted(glob.glob("scripts/mutations/*.sh"))
for script in scripts:
    r = subprocess.run(["sh", script], capture_output=True, text=True)
    out += [f"### {os.path.basename(script)} (exit {r.returncode})", "", "```", (r.stdout + r.stderr).strip(), "```", ""]

failed_mutations = [l for l in out if l.startswith("### ") and "(exit 0)" not in l]
os.makedirs("docs/evidence", exist_ok=True)
path = f"docs/evidence/{date}.md"
open(path, "w").write("\n".join(out))
print(path)
# The report is written either way, so that what failed can be read in it.
if problems or failed_mutations:
    for p in problems + failed_mutations:
        print("problem:", p.splitlines()[0])
    sys.exit(1)
PY
